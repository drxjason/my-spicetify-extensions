// This script adds additional metadata to the player, such as release date and play count.
(async function playerMetadata() {
    if (!Spicetify.Player || !Spicetify.React || !Spicetify.ReactDOM || !Spicetify.Platform || !Spicetify.GraphQL) {
        setTimeout(playerMetadata, 300)
        return
    }

    await main()
})();

// global scope objects
const { getAlbum, queryNpvArtist } = Spicetify.GraphQL.Definitions

const levels = {
    log: "[INFO]",
    warning: "[WARN]",
    error: "[ERR]"
}
const sep = '|' // pipe
const playsIcon = '\u{25B6}' // plays icon
const playsIconSvg = Spicetify.SVGIcons.play
const followIconSvg = Spicetify.SVGIcons.follow

// icons
const followIcon = '\u{2605}'

/**
 * Custom logging function
 * 
 * @param {string} level - type of message
 * @param {string} message the message in type string
 */
function clog(level, message) {
    console.log(`${level} player-metadata.js: ${message}`)
}

/**
 * Creates the elements needed to display additional metadata in the DOM
 * @param {string} uri - uri grabbed from the track player to match to the play count inside the album's data
 * @param {object} data - graphql data
 */
function createPlaycountElements(data, uri) {
    clog(levels.log, "Creating Metadata elements...")
    const artistFieldMetadata = document.querySelector(".main-trackInfo-artists")
    const artistFieldMetadataText = artistFieldMetadata?.querySelector(".e-91000-text")


    if (!artistFieldMetadata || !artistFieldMetadataText) {
        clog(levels.error, "grabbing elements again...")
        setTimeout(createPlaycountElements, 300)
    }

    // play count element creation
    const extraMetadata = document.createElement("span")
    extraMetadata.className = "main-trackInfo-extraMetadata"
    extraMetadata.style.paddingLeft = "5px"
    extraMetadata.style.color = "lightgreen"
    extraMetadata.innerHTML = `${extractPlayCount(data, uri)}`


    artistFieldMetadataText?.appendChild(extraMetadata)
    console.log(artistFieldMetadata)
    clog(levels.log, "Done!")
}

function createNpvMetadataElements(data) {
    const npWidget = document.querySelector(".main-nowPlayingWidget-nowPlaying")
    const metadataText = `<svg style="width:1em;height:1em;" class="main-nowPlayingWidget-artistMeta" fill="white">${playsIconSvg}</svg> ${abbreviateNumber(data.monthlyListeners)} <br> <svg style="width: 1em;height:1em;" class="main-nowPlayingWidget-artistMeta" fill="white">${followIconSvg}</svg> ${abbreviateNumber(data.followers)}`
    const artistMetaEl = document.querySelector(".main-nowPlayingWidget-artistMeta")

    if (artistMetaEl) {
        artistMetaEl.innerHTML = metadataText
        return
    }
    
    // monthly listeners element creation
    const artistMetadataEl = document.createElement("span")
    artistMetadataEl.className = "main-nowPlayingWidget-artistMeta encore-text-body-small"
    artistMetadataEl.style.paddingLeft = "2px" // slight padding 
    artistMetadataEl.innerHTML = metadataText

    npWidget?.appendChild(artistMetadataEl)
}
    
/**
 * Asynchronously grabs graphql data from uri, returns track data
 * 
 * @param {string} uri - album uri "spotify:album:\<base62-id\>"
 * @returns graphql track data
 */
async function getGraphQlAlbumData(uri) {
    clog(levels.log, `Retrieving album data from now playing: ${uri}`)
    return await Spicetify.GraphQL.Request(
        getAlbum,
        { uri: uri, locale: "", limit: 50, offset: 0},
    )
}

/**
 * Asynchronously grabs NPV artist data, returns artist data
 * 
 * @param {string} artistUri - artist URI from NPV
 * @param {string} trackUri - now playing track uri from NPV
 * @returns graphql contributing artist data
 */

async function getNpvArtistData(artistUri, trackUri) {
    clog(levels.log, `retrieving now playing view artist data ${artistUri} from track ${trackUri}`)
    return await Spicetify.GraphQL.Request(
        queryNpvArtist,
        { 
            artistUri: artistUri, 
            enableRelatedAudioTracks: false, 
            enableRelatedVideos: false,
            trackUri: trackUri
        }
    )
}

/**
 * Abbreivates numbers to its respective unit `K, M, B, T` to the nearest hundredths
 * Generated by ChatGPT (too lazy to make one)
 * 
 * @param {number} x - unformatted value
 * @returns 
 */
function abbreviateNumber(x) {
  if (x <= 0 || x >= 1e12) {
    throw new Error("Input must be between 0 and 1e12 (exclusive)");
  }

  const format = (num) => parseFloat(num.toFixed(2)).toString();

  const units = [
    { value: 1e12, symbol: "T" },
    { value: 1e9, symbol: "B" },
    { value: 1e6, symbol: "M" },
    { value: 1e3, symbol: "K" }
  ];

  for (let i = 0; i < units.length; i++) {
    const unit = units[i];
    if (x >= unit.value) {
      let num = x / unit.value;

      if (num >= 999.995 && i > 0) {
        const next = units[i - 1];
        return format(x / next.value) + next.symbol;
      }

      return format(num) + unit.symbol;
    }
  }

  return format(x);
}

/**
 * Grabs GraphQL "getAlbum" data, extracts, and properly abbreviates play count, and matches the uri to the correct
 * playcount, formats it to be decorated by the custom element that holds the extra metadata
 * 
 * @param {object} data - 
 * @param {string} uri 
 */
function extractPlayCount(data, uri) {
    clog(levels.log, "Extractitng play count from album track...")
    const albumTracks = data.data.albumUnion.tracksV2.items // array
    const trackData = albumTracks.find((track) => track.track.uri === uri)
    const playcountText = `${playsIcon} `

    try {
        const abbreviatedNumber = abbreviateNumber((Number(trackData.track.playcount)))
        return playcountText + abbreviatedNumber
    } catch (e) {
        return playcountText + "< 1K"
    }
    // return `${playsIcon} ${abbreviateNumber(Number(trackData.track.playcount))}`
}

/**
 * extracts main contributing artist stats (monthly listeners, followers, etc.)
 * 
 * @param {object} data - graphql npv artist data
 * @returns - user-defined object with props { followers: number, monthlyListeners: number}
 */
function extractArtistStats(data) {
    const artistData = data.data.artistUnion
    const stats = artistData.stats

    return Object.create({
        followers: Number(stats.followers),
        monthlyListeners: Number(stats.monthlyListeners)
    })
}

/**
 * Main function to write spicetify code
 * making it async for asynchronous operations, such as making graphql requests
 * 
 * TODO: create an extra field for monthly listeners and or followers   1   
 */
async function main() {

    clog(levels.log, `Separator: ${sep}, Plays Icon: ${playsIcon}`)
    // dispatch dummy event for onload
    const playerState = Spicetify.Platform.PlayerAPI.getState()
    createPlaycountElements(await getGraphQlAlbumData(playerState.item.album.uri), playerState.item.uri)
    createNpvMetadataElements(extractArtistStats(await getNpvArtistData(playerState.item.artists[0].uri, playerState.item.uri)))

    console.log(playerState.item.uri)
    Spicetify.Player.addEventListener("songchange", async (event) => {
        clog(levels.log, "Song changed, retrieving new album track data...")
        const albumUri = event.data.item.album.uri
        const artistUri = event.data.item.artists[0].uri
        
        if (!artistUri) {
            clog(levels.error, "Event listener: No artist uri was found")
        }

        const uri = event.data.item.uri
        const albumData = await getGraphQlAlbumData(albumUri)
        const artistData = await getNpvArtistData(artistUri, uri)

        clog(levels.log, "creating metadata elements...")

        // element creation
        createPlaycountElements(albumData, uri)
        createNpvMetadataElements(extractArtistStats(artistData))
        clog(levels.log, "done...")
    })
}